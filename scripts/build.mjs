/* dsh-iTab bundle builder.
 *
 * The DSH platform accepts exactly one client bundle per package
 * (exports["./client"]), so the client half is concatenated from plain
 * part files under src/client/ into src/client.bundle.js, wrapped in
 * the module-loader registration. No dependencies; run via
 * `npm run build`. Dual-use parts (model.js, tooltip.js, gitbranch.js)
 * keep real ESM exports for the node tests; the build strips the
 * `export ` keyword since the parts share one closure. No part carries
 * an `import` statement — cross-part references resolve through the
 * shared bundle scope (P, ITAB_CSS, ...). */
import { readFileSync, writeFileSync } from 'node:fs'

const parts = [
  'platform.js',
  'model.js',
  'i18n.js',
  'store.js',
  'styles.js',
  'helpers.js',
  'tooltip.js',
  'gitbranch.js',
  'hooks.js',
  'strip.js',
  'config.js',
  'entry.js',
]

let body = ''
for (const part of parts) {
  let text = readFileSync(new URL('../src/client/' + part, import.meta.url), 'utf8')
  // A no-op for parts written without exports; keeps the dual-use parts
  // (model/tooltip/gitbranch) loadable by node --test as real ESM.
  text = text.replace(/^export /gm, '')
  body += '\n/* ==================== ' + part + ' ==================== */\n' + text + '\n'
}

const out = '/* GENERATED by scripts/build.mjs — do not edit; run npm run build */\n'
  + 'window.__ModuleLoader__.load({\n'
  + "  id: 'dsh-itab',\n"
  + '  factory: (require) => {\n'
  + body
  + '\n    return createItabPlugin()\n'
  + '  },\n'
  + '})\n'

writeFileSync(new URL('../src/client.bundle.js', import.meta.url), out)
const kb = (out.length / 1024).toFixed(1)
console.log('built src/client.bundle.js (' + kb + ' KB) from ' + parts.length + ' parts')
